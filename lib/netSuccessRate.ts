export type NetGameMetric = typeof NET_GAME_METRICS[number]["key"];
export type NetSuccessGame = {
  gameId: string; season: number; week: number; seasonType: string; completed: boolean;
  homeTeam: string; awayTeam: string; homePoints: number | null; awayPoints: number | null;
  homeSuccessRate: number | null; awaySuccessRate: number | null; homeValues?: Record<string,number|null>; awayValues?: Record<string,number|null>;
  homeLogo: string | null; awayLogo: string | null; homeColor?: string | null; awayColor?: string | null; homeConference?: string | null; awayConference?: string | null;
};
export type NetSuccessRow = {
  gameId: string; winner: string; loser: string; winnerLogo: string | null; loserLogo: string | null;
  winnerColor?: string | null; loserColor?: string | null;
  winnerPoints: number; loserPoints: number; winnerSuccessRate: number; loserSuccessRate: number;
  netSuccessRate: number; tied: boolean; winnerConference: string | null; loserConference: string | null;
  seasonGames?: number;
};
export type NetSuccessReport = { season: number; week: number | "all"; seasonType: string; rows: NetSuccessRow[]; completedGames: number; missingGames: number };
const validRate = (rate: number | null): rate is number => typeof rate === "number" && Number.isFinite(rate) && rate >= 0 && rate <= 1;
export function buildNetSuccessReport(games: readonly NetSuccessGame[], fbsTeams: ReadonlySet<string>, season: number, week: number, seasonType = "regular", metricKey: NetGameMetric = "successRate"): NetSuccessReport {
  const eligible = [...new Map(games.filter(game => game.season === season && (week === -1 || game.week === week) && game.seasonType === seasonType && game.completed
    && typeof game.homePoints === "number" && Number.isFinite(game.homePoints)
    && typeof game.awayPoints === "number" && Number.isFinite(game.awayPoints)
    && fbsTeams.has(game.homeTeam) && fbsTeams.has(game.awayTeam)).map(game => [game.gameId, game])).values()];
  const rows = eligible.flatMap((game): NetSuccessRow[] => {
    const metric=NET_GAME_METRICS.find(item=>item.key===metricKey)!;
    const home=game.homeValues?game.homeValues[metricKey]??null:metricKey==="successRate"?game.homeSuccessRate:null;
    const away=game.awayValues?game.awayValues[metricKey]??null:metricKey==="successRate"?game.awaySuccessRate:null;
    const valid=(value:number|null):value is number=>metric.format==="rate"?validRate(value):typeof value==="number"&&Number.isFinite(value);
    if (!valid(home) || !valid(away)) return [];
    const homeWon = game.homePoints! >= game.awayPoints!;
    const winnerSuccessRate = homeWon ? home : away;
    const loserSuccessRate = homeWon ? away : home;
    return [{ gameId: game.gameId, winner: homeWon ? game.homeTeam : game.awayTeam, loser: homeWon ? game.awayTeam : game.homeTeam,
      winnerLogo: homeWon ? game.homeLogo : game.awayLogo, loserLogo: homeWon ? game.awayLogo : game.homeLogo,
      winnerColor: homeWon ? game.homeColor : game.awayColor, loserColor: homeWon ? game.awayColor : game.homeColor,
      winnerPoints: homeWon ? game.homePoints! : game.awayPoints!, loserPoints: homeWon ? game.awayPoints! : game.homePoints!,
      winnerConference: (homeWon ? game.homeConference : game.awayConference) ?? null, loserConference: (homeWon ? game.awayConference : game.homeConference) ?? null,
      winnerSuccessRate, loserSuccessRate, netSuccessRate: winnerSuccessRate - loserSuccessRate, tied: game.homePoints === game.awayPoints }];
  }).sort((a, b) => a.netSuccessRate - b.netSuccessRate || a.winner.localeCompare(b.winner) || a.gameId.localeCompare(b.gameId));
  return { season, week, seasonType, rows, completedGames: eligible.length, missingGames: eligible.length - rows.length };
}

export function buildSeasonNetReport(games: readonly NetSuccessGame[], fbsTeams: ReadonlySet<string>, season: number, seasonType = "regular", metricKey: NetGameMetric = "successRate"): NetSuccessReport {
  const gamesReport=buildNetSuccessReport(games,fbsTeams,season,-1,seasonType,metricKey);
  const teams=new Map<string,{team:string;logo:string|null;color:string|null;conference:string|null;sumFor:number;sumAgainst:number;count:number}>();
  for(const row of gamesReport.rows){
    for(const side of [
      {team:row.winner,logo:row.winnerLogo,color:row.winnerColor??null,conference:row.winnerConference,own:row.winnerSuccessRate,against:row.loserSuccessRate},
      {team:row.loser,logo:row.loserLogo,color:row.loserColor??null,conference:row.loserConference,own:row.loserSuccessRate,against:row.winnerSuccessRate},
    ]){
      const value=teams.get(side.team)??{team:side.team,logo:side.logo,color:side.color,conference:side.conference,sumFor:0,sumAgainst:0,count:0};
      value.sumFor+=side.own;value.sumAgainst+=side.against;value.count++;teams.set(side.team,value);
    }
  }
  const rows=[...teams.values()].map(team=>({
    gameId:`season:${season}:${seasonType}:${team.team}`,winner:team.team,loser:"Opponents",winnerLogo:team.logo,loserLogo:null,
    winnerColor:team.color,loserColor:null,winnerPoints:0,loserPoints:0,
    winnerSuccessRate:team.sumFor/team.count,loserSuccessRate:team.sumAgainst/team.count,
    netSuccessRate:(team.sumFor-team.sumAgainst)/team.count,tied:false,
    winnerConference:team.conference,loserConference:null,seasonGames:team.count,
  })).sort((a,b)=>a.netSuccessRate-b.netSuccessRate||a.winner.localeCompare(b.winner));
  return {season,week:"all",seasonType,rows,completedGames:gamesReport.completedGames,missingGames:gamesReport.missingGames};
}

export const NET_SUCCESS_SORTS = [
  {key:"netSuccessRate",label:"NET SUCCESS RATE"}, {key:"winnerSuccessRate",label:"WINNER SUCCESS RATE"},
  {key:"loserSuccessRate",label:"OPPONENT SUCCESS RATE"}, {key:"margin",label:"MARGIN OF VICTORY"},
  {key:"totalPoints",label:"TOTAL POINTS"}, {key:"winnerPoints",label:"WINNER POINTS"}, {key:"conference",label:"CONFERENCE"},
] as const;
export type NetSuccessSort = typeof NET_SUCCESS_SORTS[number]["key"];
export function canonicalNetSuccessConference(conference: string | null): string {
  if (!conference) return "Unknown";
  if (/^American( Athletic)?( Conference)?$/i.test(conference)) return "American Athletic";
  if (/^Pac[ -]?12$/i.test(conference)) return "Pac-12";
  return conference;
}
export function netSuccessConferenceGroup(conference: string | null): "power4" | "group6" | "other" {
  const name=canonicalNetSuccessConference(conference);
  if (["ACC","Big Ten","Big 12","SEC"].includes(name)) return "power4";
  if (["American Athletic","Conference USA","Mid-American","Mountain West","Pac-12","Sun Belt"].includes(name)) return "group6";
  return "other";
}
export function selectNetSuccessRows(rows: readonly NetSuccessRow[], conference: string, group: string, sort: NetSuccessSort, direction: "asc" | "desc"): NetSuccessRow[] {
  const value=(row:NetSuccessRow):number|string=>sort==="margin"?row.winnerPoints-row.loserPoints:sort==="totalPoints"?row.winnerPoints+row.loserPoints:sort==="conference"?canonicalNetSuccessConference(row.winnerConference):row[sort];
  return rows.filter(row=>{
    const conferences=[row.winnerConference,row.loserConference];
    return conferences.some(name=>(conference==="All conferences"||canonicalNetSuccessConference(name)===conference) && (group==="all"||netSuccessConferenceGroup(name)===group));
  }).sort((a,b)=>{
    const x=value(a),y=value(b);
    const difference=typeof x==="string"&&typeof y==="string"?x.localeCompare(y):Number(x)-Number(y);
    return difference*(direction==="asc"?1:-1)||a.winner.localeCompare(b.winner)||a.gameId.localeCompare(b.gameId);
  });
}

export function netGraphStep(range:number,target=8):number {
  const rough=Math.max(range/target,.0001),power=10**Math.floor(Math.log10(rough));
  return [1,2,5,10].find(multiplier=>multiplier*power>=rough)!*power;
}

// The endpoint is the scoreboard winner for both positive and negative bars.
export function netBarColor(row:NetSuccessRow):string {
  return /^#[0-9a-f]{6}$/i.test(row.winnerColor??"")?row.winnerColor!:"#475569";
}
